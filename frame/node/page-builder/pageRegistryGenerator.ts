/**
 * @file 页面注册表代码生成器
 * @description 根据页面列表生成 TypeScript 源文件作为 SSR 页面注册表
 */
import * as fs from "node:fs/promises";
import * as path from "node:path";
import { SSRPage } from "./pageRouter";

/** 页面注册表生成器配置 */
export interface PageRegistryGeneratorOptions {
    outputPath: string; /** 生成文件的输出路径 */
}

/**
 * 生成页面注册表 TypeScript 源文件
 * @description 生成包含页面模块导入、注册数组和路由查找函数的 .ts 文件
 * @param pages - 页面描述数组
 * @param options - 生成器配置
 */
export async function generatePageRegistry(
    pages: SSRPage[],
    options: PageRegistryGeneratorOptions,
): Promise<void> {
    const outputPath = path.resolve(options.outputPath);
    const outputDir = path.dirname(outputPath);
    const imports: string[] = [];
    const entries: string[] = [];

    for (const [index, page] of pages.entries()) {
        const importPath = toImportPath(outputDir, page.filePath);
        const identifier = `pageModule${index}`;
        imports.push(`import * as ${identifier} from ${JSON.stringify(importPath)};`);
        entries.push(`    { id: ${JSON.stringify(page.id)}, name: ${JSON.stringify(page.name)}, route: ${JSON.stringify(page.route)}, module: ${identifier} },`);
    }

    const content = `// This file is generated by pageRegistryGenerator. Do not edit manually.\n\n${imports.join("\n")}\n\nexport interface RegisteredPageModule {\n    id: string;\n    name: string;\n    route: string;\n    module: Record<string, unknown>;\n}\n\nexport const pageRegistry: RegisteredPageModule[] = [\n${entries.join("\n")}\n];\n\nexport interface PageMatch {\n    route: string;\n    params: Record<string, string>;\n    module: Record<string, unknown>;\n}\n\nexport function getPageModule(route: string): Record<string, unknown> | null {\n    const page = pageRegistry.find((entry) => entry.route === route);\n    return page?.module ?? null;\n}\n\nexport function getPageModuleForRoute(route: string): Record<string, unknown> | null {\n    return matchPage(route)?.module ?? null;\n}\n\nexport function matchPage(route: string): PageMatch | null {\n    const requestParts = normalizeRoute(route).split("/").filter(Boolean);\n    for (const entry of pageRegistry) {\n        const templateParts = entry.route.split("/").filter(Boolean);\n        if (templateParts.length !== requestParts.length) continue;\n        let matched = true;\n        const params: Record<string, string> = {};\n        for (let index = 0; index < templateParts.length; index++) {\n            const templatePart = templateParts[index];\n            if (templatePart.startsWith(":")) {\n                params[templatePart.slice(1)] = decodeURIComponent(requestParts[index]);\n            } else if (templatePart !== requestParts[index]) {\n                matched = false;\n                break;\n            }\n        }\n        if (matched) {\n            return { route: entry.route, params, module: entry.module };\n        }\n    }\n    return null;\n}\n\nfunction normalizeRoute(route: string): string {\n    const pathname = route.split("?", 1)[0] || "/";\n    const normalized = \`/\${pathname}\`.replace(/\\/{2,}/g, "/");\n    return normalized.length > 1 ? normalized.replace(/\\/$/, "") : normalized;\n}\n`;

    await fs.mkdir(outputDir, { recursive: true });
    await fs.writeFile(outputPath, content, "utf8");
}

/**
 * 计算从源目录到目标文件的相对导入路径
 * @param fromDir - 源目录
 * @param target - 目标文件绝对路径
 * @returns 适用于 import 的相对路径
 */
function toImportPath(fromDir: string, target: string): string {
    const relativePath = path.relative(fromDir, target).split(path.sep).join("/");
    return relativePath.startsWith(".") ? relativePath : `./${relativePath}`;
}
